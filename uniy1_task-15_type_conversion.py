# Python Program to Demonstrate Type Conversion

# Integer to Float
a = 10
b = float(a)
print("Integer to Float:", b)

# Float to Integer
x = 15.75
y = int(x)
print("Float to Integer:", y)

# Integer to String
num = 25
text = str(num)
print("Integer to String:", text)

# String to Integer
s = "50"
n = int(s)
print("String to Integer:", n)

# String to Float
p = "12.5"
q = float(p)
print("String to Float:", q)